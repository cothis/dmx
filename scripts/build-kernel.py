# Config symbols to change from Alpine's linux-virt config. None means "is not set".
CONFIG = {
    "ARM64_4K_PAGES": None,
    "ARM64_16K_PAGES": "y",
    "LOCALVERSION": f'"{LOCALVERSION}"',
    "DEBUG_INFO": None,
    "DEBUG_INFO_DWARF5": None,
    "DEBUG_INFO_NONE": "y",
    "DEBUG_INFO_BTF": None,
    "DEBUG_INFO_BTF_MODULES": None,
    "MODULE_SIG": None,
    "MODULE_SIG_ALL": None,
    "MODULE_SIG_KEY": None,
    "GCC_PLUGINS": None,
}
# Derived symbols removed so olddefconfig recomputes them for 16K pages. The VA size stays
# Alpine's 48 bits; the 16K default is 52, which needs LPA2 (Apple CPUs lack it) and trips a
# fixmap static_assert in 6.18.
DROP = {"ARM64_VA_BITS"}

BUILD_SH = r"""
set -eu
# stdout carries the result tar; everything else goes to stderr.
exec 3>&1 1>&2
cd /build
apk add --no-network --repositories-file /dev/null --force-non-repository --quiet pkgs/*.apk
mkdir src
tar -xJf linux.tar.xz -C src --strip-components=1
rm linux.tar.xz
cp config src/.config
cd src
make -s olddefconfig
for s in ARM64_16K_PAGES ARM64_VA_BITS_48 DEBUG_INFO_NONE; do
	grep -q "^CONFIG_$s=y" .config || { echo "build-kernel: CONFIG_$s did not stick" >&2; exit 1; }
done
export KBUILD_BUILD_USER=dmx KBUILD_BUILD_HOST=dmx KBUILD_BUILD_TIMESTAMP="$BUILD_TIMESTAMP"
start=$(date +%s)
make -j"$(nproc)" Image modules  # not -s: this takes long enough that progress matters
echo "build-kernel: compiled in $(( $(date +%s) - start )) s" >&2
make -s modules_install INSTALL_MOD_PATH=/out
rm -f /out/lib/modules/*/build /out/lib/modules/*/source
mkdir -p /out/boot
cp arch/arm64/boot/Image /out/boot/Image
cp .config /out/boot/config
tar -C /out -cf - boot lib >&3
"""


def alpine_config() -> str:
    with tarfile.open(guest.fetch("kernel", CACHE), "r:gz", ignore_zeros=True) as tar:
        return tar.extractfile(f"boot/config-{guest.KERNEL_RELEASE}").read().decode()


def patch_config(text: str) -> str:
    lines = []
    for line in text.splitlines():
        m = re.match(r"(?:# )?CONFIG_(\w+)[= ]", line)
        if m and (m.group(1) in CONFIG or m.group(1) in DROP):
            continue
        lines.append(line)
    for sym, value in CONFIG.items():
        lines.append(f"# CONFIG_{sym} is not set" if value is None else f"CONFIG_{sym}={value}")
    return "\n".join(lines) + "\n"


def fetch(url: str, sha256: str) -> Path:
    path = CACHE / Path(url).name
    if not path.exists():
        print(f"download {url}", file=sys.stderr)
        tmp = path.with_suffix(path.suffix + ".part")
        with urllib.request.urlopen(url) as r, open(tmp, "wb") as f:
            while chunk := r.read(1 << 20):
                f.write(chunk)
        tmp.rename(path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != sha256:
        path.unlink()
        sys.exit(f"sha256 mismatch for {path.name}: got {digest}")
    return path


def apk_url(filename: str) -> str:
    return f"{guest.ALPINE}/main/aarch64/{filename}"


def lock():
    """Resolve TOOLCHAIN_ROOTS against the current APKINDEX and print pins."""
    with urllib.request.urlopen(apk_url("APKINDEX.tar.gz")) as r:
        index = tarfile.open(fileobj=io.BytesIO(r.read()), mode="r:gz").extractfile("APKINDEX").read().decode()
    pkgs, provides = {}, {}
    for record in index.split("\n\n"):
        fields = {}
        for line in record.splitlines():
            key, _, value = line.partition(":")
            fields.setdefault(key, value)
        if "P" not in fields:
            continue
        pkgs[fields["P"]] = fields
        for p in fields.get("p", "").split():
            provides.setdefault(re.split(r"[<>=~]", p)[0], fields["P"])

    with tarfile.open(guest.fetch("minirootfs", CACHE), "r:gz") as tar:
        db = tar.extractfile("./lib/apk/db/installed").read().decode()
    installed = dict(re.findall(r"^P:(.+)\nV:(.+)$", db, re.M))

    want, todo = {}, list(TOOLCHAIN_ROOTS)
    while todo:
        dep = todo.pop()
        if dep.startswith("!"):
            continue
        name = re.split(r"[<>=~]", dep)[0]
        name = name if name in pkgs else provides.get(name)
        if name is None:
            sys.exit(f"cannot resolve {dep}")
        if name in want or installed.get(name) == pkgs[name]["V"]:
            continue
        want[name] = pkgs[name]
        todo.extend(pkgs[name].get("D", "").split())

    print("TOOLCHAIN = {")
    for name in sorted(want):
        filename = f"{name}-{want[name]['V']}.apk"
        with urllib.request.urlopen(apk_url(filename)) as r:
            data = r.read()
        (CACHE / filename).write_bytes(data)
        print(f'    "{filename}": "{hashlib.sha256(data).hexdigest()}",')
    print("}")


def build(args):
    if not TOOLCHAIN:
        sys.exit("TOOLCHAIN is empty; run with --lock and paste the result")
    out = CACHE / f"kernel-{RELEASE}.tar"
    payload = io.BytesIO()
    with tarfile.open(fileobj=payload, mode="w") as tar:
        def add(name, data):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
        add("config", patch_config(alpine_config()).encode())
        add("build.sh", BUILD_SH.encode())
        tar.add(fetch(SOURCE["url"], SOURCE["sha256"]), "linux.tar.xz")
        for filename, sha256 in TOOLCHAIN.items():
            tar.add(fetch(apk_url(filename), sha256), f"pkgs/{filename}")

    # Boot a guest with the stock Alpine kernel, kept apart from the user's guest, so building
    # the dmx kernel never depends on an earlier dmx kernel.
    bootstrap = CACHE / "bootstrap"
    subprocess.run([sys.executable, "-I", str(ROOT / "scripts" / "build-guest.py"), "--kernel", "alpine",
                    "--cache", str(CACHE), "--out", str(bootstrap / "guest")], check=True, stdout=subprocess.DEVNULL)
    dmx = ROOT / ".build" / "release" / "dmx"
    script = (
        "set -e; mkdir /build /out; mount -t tmpfs -o size=90% tmpfs /build; "
        "cd /build; tar -xf -; "
        f"BUILD_TIMESTAMP='{args.timestamp}' sh build.sh"
    )
    cmd = [str(dmx), "boot", "--memory", args.memory, "--", "sh", "-c", script]
    start = time.monotonic()
    tmp = out.with_suffix(".tar.part")
    with open(tmp, "wb") as f:
        proc = subprocess.run(cmd, input=payload.getvalue(), stdout=f, env={**os.environ, "DMX_HOME": str(bootstrap)})
    if proc.returncode != 0:
        tmp.unlink(missing_ok=True)
        sys.exit(f"kernel build failed (exit {proc.returncode})")
    tmp.rename(out)
    with tarfile.open(out) as tar:
        names = tar.getnames()
    if "boot/Image" not in names and "./boot/Image" not in names:
        sys.exit(f"{out} has no boot/Image")
    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    print(f'{{"ok": true, "out": "{out}", "sha256": "{digest}", "seconds": {time.monotonic() - start:.0f}}}')


def main():
    global CACHE
    home = Path(os.environ.get("DMX_HOME", Path.home() / ".dmx"))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", type=Path, default=home / "cache")
    ap.add_argument("--memory", default="8G", help="memory ceiling of the build VM")
    ap.add_argument("--timestamp", default="2026-01-01", help="KBUILD_BUILD_TIMESTAMP")
    ap.add_argument("--lock", action="store_true", help="print TOOLCHAIN pins for the current APKINDEX")
    args = ap.parse_args()
    CACHE = args.cache
    CACHE.mkdir(parents=True, exist_ok=True)
    lock() if args.lock else build(args)


if __name__ == "__main__":
    main()
