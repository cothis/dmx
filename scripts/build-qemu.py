# Alpine's build-static configure line, for x86_64-linux-user only. --enable-kvm and
# --enable-seccomp from its common flags apply to system emulation, which this does not build.
BUILD_SH = r"""
set -eu
# stdout carries the binary; everything else goes to stderr.
exec 3>&1 1>&2
cd /build
apk add --no-network --repositories-file /dev/null --force-non-repository --quiet pkgs/*.apk
mkdir src
tar -xJf qemu.tar.xz -C src --strip-components=1
rm qemu.tar.xz
cd src
for p in $PATCHES; do patch -p1 -s <../patches/$p; done
mkdir build-static
cd build-static
export CFLAGS="-O2 -fstack-clash-protection -Wformat -Werror=format-security"
../configure --prefix=/usr --localstatedir=/var --sysconfdir=/etc --libexecdir=/usr/lib/qemu \
	--python=/usr/bin/python3 --disable-glusterfs --disable-debug-info --disable-bsd-user \
	--disable-werror --cc=gcc --target-list=x86_64-linux-user \
	--enable-linux-user --disable-system --static --disable-brlapi --disable-bpf --disable-cap-ng \
	--disable-capstone --disable-curl --disable-curses --disable-docs --disable-gcrypt \
	--disable-gnutls --disable-gtk --disable-guest-agent --disable-guest-agent-msi --disable-libnfs \
	--disable-mpath --disable-nettle --disable-numa --disable-sdl --disable-spice --disable-tools
start=$(date +%s)
ninja qemu-x86_64
echo "build-qemu: compiled in $(( $(date +%s) - start )) s" >&2
echo "build-qemu: links $(ninja -t commands qemu-x86_64 | tail -n 1 | tr ' ' '\n' | grep -E '^-l|[.]a$' | grep -v '^lib[a-z_-]*[.]a$' | sort -u | tr '\n' ' ')" >&2
strip qemu-x86_64
./qemu-x86_64 -version >&2
cat qemu-x86_64 >&3
"""


def build(args):
    if not TOOLCHAIN:
        sys.exit("TOOLCHAIN is empty; run with --lock and paste the result")
    out = CACHE / guest.DMX_QEMU
    patches = list(ALPINE_PATCHES) + ["dmx-guest-base.patch"]
    payload = io.BytesIO()
    with tarfile.open(fileobj=payload, mode="w") as tar:
        def add(name, data):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
        add("build.sh", BUILD_SH.encode())
        add("patches/dmx-guest-base.patch", GUEST_BASE_PATCH.encode())
        tar.add(kernel.fetch(SOURCE["url"], SOURCE["sha256"]), "qemu.tar.xz")
        for name, sha256 in ALPINE_PATCHES.items():
            tar.add(kernel.fetch(f"{APORTS}/{name}", sha256), f"patches/{name}")
        for pin, sha256 in TOOLCHAIN.items():
            tar.add(kernel.fetch(kernel.apk_url(pin), sha256), f"pkgs/{Path(pin).name}")

    # The bootstrap guest (stock Alpine kernel) that `make kernel` uses, so this does not depend
    # on an earlier dmx guest either.
    bootstrap = CACHE / "bootstrap"
    subprocess.run([sys.executable, "-I", str(ROOT / "scripts" / "build-guest.py"), "--kernel", "alpine",
                    "--cache", str(CACHE), "--out", str(bootstrap / "guest")], check=True, stdout=subprocess.DEVNULL)
    dmx = ROOT / ".build" / "release" / "dmx"
    script = ("set -e; mkdir /build; mount -t tmpfs -o size=90% tmpfs /build; cd /build; tar -xf -; "
              f"PATCHES='{' '.join(patches)}' sh build.sh")
    cmd = [str(dmx), "boot", "--memory", args.memory, "--boot-memory", args.memory, "--", "sh", "-c", script]
    start = time.monotonic()
    tmp = out.with_name(out.name + ".part")
    with open(tmp, "wb") as f:
        proc = subprocess.run(cmd, input=payload.getvalue(), stdout=f, env={**os.environ, "DMX_HOME": str(bootstrap)})
    if proc.returncode != 0 or tmp.read_bytes()[:4] != b"\x7fELF":
        tmp.unlink(missing_ok=True)
        sys.exit(f"qemu build failed (exit {proc.returncode})")
    tmp.chmod(0o755)
    tmp.rename(out)
    digest = hashlib.sha256(out.read_bytes()).hexdigest()
    print(f'{{"ok": true, "out": "{out}", "bytes": {out.stat().st_size}, "sha256": "{digest}", "seconds": {time.monotonic() - start:.0f}}}')


